/** Shared domain types for the Kobo frontend mock. All data is local/demo. */

export type TxType = "income" | "expense" | "refund" | "transfer";

export type TxCategory =
  | "Food"
  | "Transport"
  | "Airtime/Data"
  | "Shopping"
  | "Bills"
  | "Transfer"
  | "Income"
  | "Savings";

export interface Transaction {
  id: string;
  merchant: string;
  category: TxCategory;
  type: TxType;
  amount: number;
  /** Days ago from "now" — keeps server/client rendering deterministic. */
  daysAgo: number;
  /** Fixed display time, e.g. "1:24 PM". */
  time: string;
  note?: string;
  /** Marks transactions generated by simulated user actions in the session. */
  simulated?: boolean;
}

export type GoalAccent = "teal" | "gold" | "coral" | "mint";

export interface SavingsGoal {
  id: string;
  name: string;
  icon: "shield" | "party" | "laptop" | "gift";
  saved: number;
  target: number;
  /** Friendly status line: days left or encouragement. */
  status: string;
  accent: GoalAccent;
}

export interface Budget {
  id: string;
  category: Exclude<TxCategory, "Transfer" | "Income" | "Savings">;
  icon: "food" | "transport" | "data" | "shopping" | "bills";
  limit: number;
  spent: number;
}

export type BudgetStatus = "safe" | "warning" | "limit" | "over";

export type InsightTone = "teal" | "gold" | "coral" | "mint" | "rose";

export interface Insight {
  id: string;
  title: string;
  body: string;
  tone: InsightTone;
  icon: "trending" | "target" | "bus" | "laptop" | "calendar" | "coins";
  action: { label: string; href: "/budget" | "/learn" | "/save" | "/insights" };
}

export interface Achievement {
  id: string;
  name: string;
  description: string;
  icon: "sparkles" | "flame" | "target" | "badge" | "coins" | "calendar" | "trophy";
  unlocked: boolean;
  unlockedLabel?: string;
}

export interface Contact {
  id: string;
  name: string;
  initials: string;
  bank: string;
  handle: string;
  recent?: boolean;
}

export type LearnCategory =
  | "Saving"
  | "Budgeting"
  | "Spending"
  | "Emergency Funds"
  | "Money Goals"
  | "Understanding Interest"
  | "Digital Finance Safety";

export interface Article {
  id: string;
  title: string;
  description: string;
  category: LearnCategory;
  minutes: number;
  progress: number; // 0–100
  icon: "shield" | "pie" | "coins" | "umbrella" | "flag" | "percent" | "lock";
}

export interface StreakDay {
  label: string;
  day: string;
  done: boolean;
}

export interface Streak {
  days: number;
  savedToday: boolean;
  nextMilestone: number;
  week: StreakDay[];
}

export interface Toast {
  id: number;
  message: string;
  tone: "teal" | "gold" | "coral" | "rose";
}

export interface MilestoneEvent {
  id: number;
  goalId: string;
  percent: number;
  complete: boolean;
}
